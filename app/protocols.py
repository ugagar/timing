from typing import Protocol

from app.models import DatetimeInterval, Event, EventType


class EventRepository(Protocol):
    def save(self, event: Event) -> None: ...
    def update(self, event: Event) -> None: ...
    def get(self, event_type: EventType, interval: DatetimeInterval) -> list[Event]: ...
    def delete(self, event: Event) -> None: ...


class EventTypeRepository(Protocol):
    def get_by_name(name: str) -> EventType: ...
    def create(): ...
    def delete(): ...


class Repository(Protocol): 
    @property
    def event(self) -> EventRepository: ...

    @property
    def event_type(self) -> EventTypeRepository: ...
    